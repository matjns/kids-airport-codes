#!/usr/bin/env python3
"""Build Sources/AirportCodesCore/AirportData.swift from OurAirports (public domain)
plus the curated lists in this folder.

Inputs: airports.csv and countries.csv from https://ourairports.com/data/
Usage: python3 Data/generate.py <folder with airports.csv and countries.csv>

Only airports that OurAirports lists as large or medium, with scheduled
passenger service and a 3-letter IATA code, make it into the game. Any code in
tiers.txt that fails that check is skipped and printed.
"""
import csv, json, re, sys, collections
from pathlib import Path

here = Path(__file__).resolve().parent
root = here.parent
src = Path(sys.argv[1] if len(sys.argv) > 1 else ".")

# Keep the hard tier around 400 and spread around the world.
HARD_CAP = {"US": 65, "CA": 8}
HARD_CAP_OTHER = 5

airports = {r["iata_code"]: r for r in csv.DictReader(open(src / "airports.csv", encoding="utf-8")) if r["iata_code"]}
countries = {r["code"]: r["name"] for r in csv.DictReader(open(src / "countries.csv", encoding="utf-8"))}

def valid(code):
    r = airports.get(code)
    return (r is not None and re.fullmatch(r"[A-Z]{3}", code) and r["scheduled_service"] == "yes"
            and r["type"] in ("large_airport", "medium_airport"))

def lines(name):
    for line in open(here / name, encoding="utf-8"):
        line = line.strip()
        if line and not line.startswith("#"):
            yield line

names = {}
for line in lines("names.txt"):
    code, city, aliases = (line.split("|") + [""])[:3]
    names[code] = (city, [a.strip() for a in aliases.split(",") if a.strip()])
facts = {}
for line in lines("facts.txt"):
    code, fact = line.split("|", 1)
    facts[code] = fact

def clean_city(m):
    m = re.sub(r"\s*\(.*?\)", "", m)
    return re.split(r"[,/]", m)[0].strip()

def short_name(name):
    for tail in [" International Airport", " Airport", " International"]:
        if name.endswith(tail):
            return name[: -len(tail)]
    return name

tier_of = {}
order = []
skipped = []
for line in lines("tiers.txt"):
    tier, codes = line.split(":", 1)
    for code in codes.split():
        if code in tier_of:
            continue
        if not valid(code):
            skipped.append(code)
            continue
        tier_of[code] = tier.strip()
        order.append(code)

per_country = collections.Counter()
out = []
for code in order:
    r = airports[code]
    tier = tier_of[code]
    cc = r["iso_country"]
    if tier == "hard" and code not in facts:
        cap = HARD_CAP.get(cc, HARD_CAP_OTHER)
        if per_country[cc] >= cap:
            continue
        per_country[cc] += 1
    city, aliases = names.get(code, (clean_city(r["municipality"]), []))
    muni = clean_city(r["municipality"])
    accepted = [a for a in dict.fromkeys(aliases + [muni, short_name(r["name"])]) if a and a.lower() != city.lower()]
    out.append({
        "code": code,
        "name": r["name"],
        "city": city,
        "country": countries.get(cc, cc),
        "tier": {"easy": "easy", "medium": "medium", "hard": "advanced"}[tier],
        "aliases": accepted,
        "fact": facts.get(code, ""),
    })

missing_facts = [c for c in facts if c not in {a["code"] for a in out}]
assert not missing_facts, f"facts for airports not in the game: {missing_facts}"
codes = [a["code"] for a in out]
assert len(codes) == len(set(codes))

blob = json.dumps(out, ensure_ascii=False, separators=(",", ":"))
chunks = [blob[i:i + 4000] for i in range(0, len(blob), 4000)]
swift = ["// Generated by Data/generate.py from OurAirports (public domain). Do not edit.",
         "enum AirportListData {", "    static let json: String = ["]
swift += ['        #"' + c + '"#,' for c in chunks]
swift += ["    ].joined()", "}", ""]
(root / "Sources/AirportCodesCore/AirportData.swift").write_text("\n".join(swift), encoding="utf-8")

count = collections.Counter(a["tier"] for a in out)
print("airports", len(out), dict(count), "skipped (not verified):", " ".join(skipped))
